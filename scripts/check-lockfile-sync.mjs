#!/usr/bin/env node
/**
 * Fail the build when `bun.lock` does not match the `package.json` files.
 *
 * The rule ("commit the lockfile in the SAME commit as the package.json
 * change") existed only as advice in AGENTS.md, and was skipped three times in
 * a single day — twice in ways that contributed to publishing a release from a
 * state that was not the committed one, burning a version number npm will never
 * let us reuse.
 *
 * WHY THIS DOES NOT USE `--frozen-lockfile`
 *
 * That is the obvious gate and it does not work here. Measured on bun 1.3.14
 * against this repo, `bun install --frozen-lockfile` exits 0 on BOTH shapes of
 * desync we actually shipped:
 *
 *   - a workspace package's own `version` bumped without regenerating the
 *     lockfile (what the core 15.0.0 / services 23.3.0 bump did) — exit 0;
 *   - a dependency RANGE widened to something the lockfile does not record
 *     (`^15.0.0` → `>=15.0.0`) — exit 0.
 *
 * It only fails when a range resolves to nothing at all, which is a resolution
 * error rather than a sync check. So the flag would have caught none of the
 * three incidents while reading like enforcement — worse than no gate.
 *
 * WHAT THIS DOES INSTEAD
 *
 * Regenerates the lockfile (a plain `bun install`, which rewrites `bun.lock` to
 * whatever the manifests currently imply) and asks git whether the file moved.
 * A tracked file changing IS the desync, with no interpretation needed. That
 * distinguishes it from the `--frozen-lockfile` false positive AGENTS.md
 * records: this check never asks bun to judge staleness, it compares committed
 * bytes to regenerated bytes.
 *
 * Verified stable on a synced tree across four runs — two with a warm install
 * cache and two with a cold one, matching a fresh CI runner — with zero
 * spurious diffs.
 */

import { execFileSync } from 'node:child_process';
import { readFileSync } from 'node:fs';

const LOCKFILE = 'bun.lock';

/** Run a command, returning stdout. Throws on a non-zero exit. */
function run(command, args, options = {}) {
  return execFileSync(command, args, { encoding: 'utf8', ...options });
}

/** Whether git reports the lockfile as modified relative to HEAD. */
function lockfileIsDirty() {
  try {
    run('git', ['diff', '--quiet', '--', LOCKFILE]);
    return false;
  } catch {
    return true;
  }
}

/**
 * The workspace entries a lockfile diff falls inside.
 *
 * `bun.lock` is JSONC (trailing commas), so it is not `JSON.parse`-able and a
 * hand-rolled tolerant parser would be a liability. Line-oriented instead: take
 * the changed line numbers from a zero-context diff, then scan UP the
 * regenerated file for the nearest enclosing `"<key>": {` at the workspace
 * indent level. Exact, and it cannot be confused by the file's contents.
 */
function changedWorkspaces() {
  const diff = run('git', ['diff', '--unified=0', '--', LOCKFILE]);
  const lines = readFileSync(LOCKFILE, 'utf8').split('\n');

  // A workspace entry is a 4-space-indented key: `    "packages/core": {`.
  // The repo root itself is keyed `""`.
  const WORKSPACE_KEY = /^ {4}"([^"]*)": \{$/;

  const touched = new Set();
  for (const header of diff.matchAll(/^@@ -\S+ \+(\d+)(?:,(\d+))? @@/gm)) {
    const start = Number(header[1]);
    const count = header[2] === undefined ? 1 : Number(header[2]);
    // A pure deletion reports the line BEFORE which content was removed.
    for (let line = start; line < start + Math.max(count, 1); line += 1) {
      for (let cursor = line - 1; cursor >= 0; cursor -= 1) {
        const match = WORKSPACE_KEY.exec(lines[cursor] ?? '');
        if (match) {
          touched.add(match[1] === '' ? '<repo root>' : match[1]);
          break;
        }
      }
    }
  }
  return [...touched].sort();
}

if (lockfileIsDirty()) {
  console.error(
    `${LOCKFILE} already has uncommitted changes, so this check cannot attribute\n` +
      'what a fresh install would alter. Commit or stash it, then re-run.',
  );
  process.exit(1);
}

run('bun', ['install'], { stdio: ['ignore', 'ignore', 'inherit'] });

if (!lockfileIsDirty()) {
  console.log(`${LOCKFILE} is in sync with every package.json.`);
  process.exit(0);
}

const packages = changedWorkspaces();

console.error(
  `\n${LOCKFILE} is OUT OF SYNC with the package.json files.\n\n` +
    'A plain `bun install` rewrote it, which means the committed lockfile does not\n' +
    'reflect the current manifests. Affected workspace package(s):\n' +
    `${packages.map((name) => `  - ${name}`).join('\n') || '  (none identified — see the diff below)'}\n\n` +
    'Fix: run `bun install` and commit the resulting bun.lock in the SAME commit as\n' +
    'the package.json change. A dependency or version bump without its lockfile is\n' +
    'how a release gets published from a state that was never committed.\n',
);
console.error(run('git', ['--no-pager', 'diff', '--', LOCKFILE]));
process.exit(1);
